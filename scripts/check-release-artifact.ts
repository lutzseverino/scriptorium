// Check the public schema and docs after publication, or a candidate tree
// through the same URL resolver in the test suite.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { Ajv, type AnySchemaObject } from "ajv";

export const configurationSchemaUrl =
  "https://raw.githubusercontent.com/lutzseverino/scriptorium/scriptorium-v4.0.0/schemas/factory-configuration.schema.json";

type ReadUrl = (url: string) => Promise<string>;

export function checkConfigurationSchema(schema: AnySchemaObject): void {
  const validate = new Ajv({ allErrors: true, strictTypes: true }).compile(
    schema,
  );
  const fixture = (name: string) =>
    JSON.parse(
      readFileSync(
        new URL(
          `../test/fixtures/factory-configuration/${name}.json`,
          import.meta.url,
        ),
        "utf8",
      ),
    );
  const check = (value: unknown, expected: boolean, name: string) =>
    assert.equal(
      validate(value),
      expected,
      `${name}: ${JSON.stringify(validate.errors)}`,
    );
  for (const name of ["valid", "version-3"]) {
    const configuration = fixture(name);
    check(configuration, true, name);
    check(
      { ...configuration, $schema: schema.$id },
      true,
      `${name} with metadata`,
    );
    for (const value of [null, 3, {}, [], "", " schema.json", "schema.json "])
      check(
        { ...configuration, $schema: value },
        false,
        `${name} invalid metadata`,
      );
    for (const version of [1, 4, "2", "3", null])
      check(
        { ...configuration, version },
        false,
        `${name} unsupported version`,
      );
    check({ ...configuration, extra: true }, false, `${name} unknown field`);
    check(
      {
        ...configuration,
        labels: { ...configuration.labels, extra: "unknown" },
      },
      false,
      `${name} unknown label`,
    );
    check(
      {
        ...configuration,
        contractResult: { ...configuration.contractResult, extra: true },
      },
      false,
      `${name} unknown identity field`,
    );
    check(
      {
        ...configuration,
        comments: {
          run: "Run summary.",
          action: "Please act.",
          close: "Closed.",
          disclaimer: "> Generated by the factory.",
          triageDisclaimer: "> Generated during triage.",
        },
      },
      true,
      `${name} current comment fields`,
    );
    for (const field of ["pause", "failure", "awaitingMerge"])
      check(
        { ...configuration, comments: { [field]: "Legacy." } },
        false,
        `${name} removed comment ${field}`,
      );
    for (const field of ["disclaimer", "triageDisclaimer"])
      for (const value of [null, 3, "", " leading", "trailing "])
        check(
          { ...configuration, comments: { [field]: value } },
          false,
          `${name} invalid ${field}`,
        );
    check(
      { ...configuration, comments: { extra: "unknown" } },
      false,
      `${name} unknown comment`,
    );
  }
  for (const name of [
    "empty",
    "malformed-objects",
    "missing-labels",
    "null",
    "array",
    "missing",
    "unknown",
    "malformed",
  ])
    check(fixture(name), false, name);
  const v2 = fixture("valid");
  const v3 = fixture("version-3");
  check({ ...v2, runKinds: v3.runKinds }, false, "v2 refuses v3 fields");
  check({ ...v3, skill: "implement" }, false, "v3 refuses v2 fields");
  check(
    { ...v3, labels: { ...v3.labels, needsInput: "question" } },
    false,
    "v3 refuses v2 labels",
  );
  check({ ...v3, runKinds: {} }, false, "v3 requires implement");
  for (const kind of ["triage", "implement", "review"]) {
    for (const resultLabels of [[], ["model:", "priority:"]])
      check(
        {
          ...v3,
          runKinds: {
            ...v3.runKinds,
            [kind]: { ...v3.runKinds[kind], resultLabels },
          },
        },
        true,
        `${kind} result label families`,
      );
    for (const resultLabels of [
      null,
      "model:",
      [3],
      [""],
      [" trailing "],
      ["model:", "model:"],
    ])
      check(
        {
          ...v3,
          runKinds: {
            ...v3.runKinds,
            [kind]: { ...v3.runKinds[kind], resultLabels },
          },
        },
        false,
        `${kind} invalid result label families`,
      );
  }
  check(
    {
      ...v3,
      runKinds: { implement: v3.runKinds.implement },
      labels: {
        ready: "queued",
        running: "working",
        paused: "waiting",
        failed: "broken",
      },
    },
    true,
    "minimal v3 needs no triage label",
  );
  const { triage: _triage, ...labels } = v3.labels;
  check({ ...v3, labels }, false, "triage needs its label");
  for (const kind of [
    { skill: "triage", arguments: "#{pullRequest}" },
    { skill: "triage", arguments: 3 },
    { skill: "triage", arguments: "#{issue}", differentProvider: true },
  ])
    check(
      { ...v3, runKinds: { ...v3.runKinds, triage: kind } },
      false,
      "invalid triage kind",
    );
  check(
    {
      ...v3,
      runKinds: {
        ...v3.runKinds,
        review: {
          skill: "review",
          arguments: "#{pullRequest}",
          differentProvider: "yes",
        },
      },
    },
    false,
    "review provider flag must be boolean",
  );
}

export async function checkReleaseArtifact(
  schemaUrl = configurationSchemaUrl,
  readUrl: ReadUrl = async (url) => {
    const response = await fetch(url, { signal: AbortSignal.timeout(15_000) });
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    return response.text();
  },
): Promise<void> {
  const location =
    /^https:\/\/raw\.githubusercontent\.com\/lutzseverino\/scriptorium\/(scriptorium-v\d+\.\d+\.\d+)\/schemas\/factory-configuration\.schema\.json$/.exec(
      schemaUrl,
    );
  assert.ok(location, "schema URL must name a Scriptorium release tag");
  const schema = JSON.parse(await readUrl(schemaUrl));
  assert.equal(
    schema.$id,
    schemaUrl,
    "schema identity must match its public URL",
  );
  checkConfigurationSchema(schema);
  for (const name of ["factory-configuration", "sandbox-image"]) {
    const path = `docs/usage/${name}.md`;
    const link = `https://github.com/lutzseverino/scriptorium/blob/${location[1]}/${path}`;
    assert.ok(
      schema.description.includes(link),
      `schema description must link ${link}`,
    );
    const document = await readUrl(
      `https://raw.githubusercontent.com/lutzseverino/scriptorium/${location[1]}/${path}`,
    );
    assert.match(document, /^# /m, `${link} must resolve to documentation`);
  }
}

if (import.meta.main) {
  await checkReleaseArtifact(process.argv[2]);
  process.stdout.write(
    "Published configuration schema, fixtures and same-tag documentation passed.\n",
  );
}
